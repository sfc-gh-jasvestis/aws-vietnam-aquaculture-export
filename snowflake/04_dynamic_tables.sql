-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT exporter.ID AS ENTITY_ID, exporter.NAME AS ENTITY_NAME,
       exporter.REGION, exporter.CATEGORY, exporter.RISK_TIER, exporter.STATUS,
       COUNT(*) AS EVENT_COUNT,
       SUM(observation.SHIPMENT_COUNT) AS SHIPMENT_COUNT,
       SUM(observation.SHIPMENT_VALUE_USD) AS SHIPMENT_VALUE_USD,
       SUM(observation.ISSUE_COUNT) AS ISSUE_COUNT,
       SUM(observation.REJECTED_COUNT) AS REJECTED_COUNT,
       SUM(observation.LATE_DELIVERY) AS LATE_DELIVERY_COUNT,
       SUM(observation.LAB_TEST_DUE) AS LAB_TEST_DUE,
       SUM(observation.LAB_TEST_DONE) AS LAB_TEST_DONE,
       100.0 * (SUM(observation.SHIPMENT_COUNT) - SUM(observation.ISSUE_COUNT)) / NULLIF(SUM(observation.SHIPMENT_COUNT), 0) AS CLEAN_SHIPMENT_PCT,
       100.0 * SUM(observation.REJECTED_COUNT) / NULLIF(SUM(observation.ISSUE_COUNT), 0) AS ISSUE_REJECT_PCT,
       100.0 * SUM(observation.LAB_TEST_DONE) / NULLIF(SUM(observation.LAB_TEST_DUE), 0) AS LAB_TEST_PCT,
       AVG(observation.DOC_DISCREPANCY_PCT) AS AVG_DOC_DISCREPANCY_PCT,
       MAX(observation.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.EXPORTER_DAILY observation
JOIN RAW.EXPORTERS exporter ON exporter.ID = observation.ENTITY_ID
GROUP BY exporter.ID, exporter.NAME, exporter.REGION, exporter.CATEGORY, exporter.RISK_TIER, exporter.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(SHIPMENT_COUNT) AS SHIPMENT_COUNT, SUM(SHIPMENT_VALUE_USD) AS SHIPMENT_VALUE_USD,
       SUM(ISSUE_COUNT) AS ISSUE_COUNT, SUM(REJECTED_COUNT) AS REJECTED_COUNT,
       100.0 * SUM(REJECTED_COUNT) / NULLIF(SUM(ISSUE_COUNT), 0) AS ISSUE_REJECT_PCT
FROM RAW.EXPORTER_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.ISSUE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT ISSUE_TYPE, SUM(ISSUE_COUNT) AS ISSUE_COUNT,
       SUM(REJECTED_COUNT) AS REJECTED_COUNT,
       SUM(LATE_DELIVERY) AS LATE_DELIVERY_COUNT,
       SUM(SHIPMENT_VALUE_USD) AS EXPOSED_VALUE_USD,
       100.0 * SUM(REJECTED_COUNT) / NULLIF(SUM(ISSUE_COUNT), 0) AS ISSUE_REJECT_PCT
FROM RAW.EXPORTER_DAILY
WHERE ISSUE_COUNT > 0
GROUP BY ISSUE_TYPE;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(SHIPMENT_COUNT) AS SHIPMENTS, SUM(ISSUE_COUNT) AS ISSUES,
         SUM(REJECTED_COUNT) AS REJECTED, SUM(LATE_DELIVERY) AS BREACHES, SUM(SHIPMENT_VALUE_USD) AS SHIPMENT_VALUE_USD,
         SUM(LAB_TEST_DUE) AS LAB_TEST_DUE, SUM(LAB_TEST_DONE) AS LAB_TEST_DONE,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.EXPORTER_DAILY
), book AS (SELECT COUNT(*) AS EXPORTER_COUNT FROM RAW.EXPORTERS),
documents AS (
  SELECT 100.0 * SUM(LEAST(ON_FILE_QTY, REQUIRED_QTY)) / NULLIF(SUM(REQUIRED_QTY), 0) AS COVERAGE_PCT,
         SUM(PENDING_QTY) AS PENDING
  FROM RAW.COMPLIANCE_DOCUMENTS
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'Clean Consignment Rate' AS TITLE,
         100.0 * (SHIPMENTS - ISSUES) / NULLIF(SHIPMENTS, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'Consignment Issues Raised', ISSUES, '' FROM observations
  UNION ALL SELECT 3, 'Import Rejections', REJECTED, '' FROM observations
  UNION ALL SELECT 4, 'Issue Rejection Rate', 100.0 * REJECTED / NULLIF(ISSUES, 0), '%' FROM observations
  UNION ALL SELECT 5, 'Late Arrivals', BREACHES, '' FROM observations
  UNION ALL SELECT 6, 'Export Value (USD M)', SHIPMENT_VALUE_USD / 1e6, '' FROM observations
  UNION ALL SELECT 7, 'Consignments Dispatched', SHIPMENTS, '' FROM observations
  UNION ALL SELECT 8, 'Residue Lab Test Compliance', 100.0 * LAB_TEST_DONE / NULLIF(LAB_TEST_DUE, 0), '%' FROM observations
  UNION ALL SELECT 9, 'Seafood Exporters Monitored', EXPORTER_COUNT, '' FROM book
  UNION ALL SELECT 10, 'Export Document Coverage', COVERAGE_PCT, '%' FROM documents
  UNION ALL SELECT 11, 'Export Documents Pending', PENDING, '' FROM documents
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                WHEN metrics.SORT_ORDER = 1 THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 2), '990.00'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.ISSUE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
