-- Shipment-rejection risk scoring and shipment-issue forecast over the synthetic snapshot.
-- Predicts P(rejected shipment for the exporter in the next 7 days) per exporter and
-- reports out-of-time holdout metrics; nothing is seeded as a prediction.
USE DATABASE IDENTIFIER($DEMO_DB);
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE VIEW ML.REJECT_FEATURES AS
SELECT r.ENTITY_ID, r.EVENT_DATE, a.CATEGORY, a.RISK_TIER, a.EXPORTER_AGE_YEARS,
       r.DOC_DISCREPANCY_PCT, r.AVG_CERT_TURNAROUND_HRS,
       AVG(r.DOC_DISCREPANCY_PCT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 6 PRECEDING AND CURRENT ROW) AS DOC_DISCREPANCY_7D,
       SUM(r.REJECTED_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 29 PRECEDING AND CURRENT ROW) AS REJECTED_30D,
       IFF(SUM(r.REJECTED_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) > 0,
           'REJECT', 'OK') AS LABEL,
       COUNT(*) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) AS FUTURE_DAYS
FROM RAW.EXPORTER_DAILY r JOIN RAW.EXPORTERS a ON a.ID = r.ENTITY_ID
-- City-wide storm port closures are not exporter-driven, so they are excluded from training.
WHERE r.ISSUE_TYPE <> 'Storm port closure';

-- Time-based split: train on older labelled days, hold out the most recent 14 labelled days.
CREATE VIEW ML.REJECT_TRAIN AS
SELECT CATEGORY, RISK_TIER, EXPORTER_AGE_YEARS, DOC_DISCREPANCY_PCT, AVG_CERT_TURNAROUND_HRS, DOC_DISCREPANCY_7D, REJECTED_30D, LABEL
FROM ML.REJECT_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE < DATEADD('day', -21, CURRENT_DATE());

CREATE VIEW ML.REJECT_HOLDOUT AS
SELECT ENTITY_ID, EVENT_DATE, CATEGORY, RISK_TIER, EXPORTER_AGE_YEARS, DOC_DISCREPANCY_PCT, AVG_CERT_TURNAROUND_HRS, DOC_DISCREPANCY_7D, REJECTED_30D, LABEL
FROM ML.REJECT_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE >= DATEADD('day', -21, CURRENT_DATE());

CREATE SNOWFLAKE.ML.CLASSIFICATION ML.REJECT_RISK_MODEL(
  INPUT_DATA => TABLE(ML.REJECT_TRAIN),
  TARGET_COLNAME => 'LABEL'
);

-- Out-of-time holdout: precision/recall at 0.5 versus the base rate.
CREATE TABLE ML.REJECT_RISK_HOLDOUT_METRICS AS
WITH scored AS (
  SELECT LABEL, ML.REJECT_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'RISK_TIER', RISK_TIER, 'EXPORTER_AGE_YEARS', EXPORTER_AGE_YEARS,
           'DOC_DISCREPANCY_PCT', DOC_DISCREPANCY_PCT, 'AVG_CERT_TURNAROUND_HRS', AVG_CERT_TURNAROUND_HRS,
           'DOC_DISCREPANCY_7D', DOC_DISCREPANCY_7D, 'REJECTED_30D', REJECTED_30D)):probability:REJECT::FLOAT AS P
  FROM ML.REJECT_HOLDOUT
)
SELECT COUNT(*) AS N,
       AVG(IFF(LABEL = 'REJECT', 1, 0)) AS BASE_RATE,
       SUM(IFF(P >= 0.5 AND LABEL = 'REJECT', 1, 0)) / NULLIF(SUM(IFF(P >= 0.5, 1, 0)), 0) AS PRECISION_AT_50,
       SUM(IFF(P >= 0.5 AND LABEL = 'REJECT', 1, 0)) / NULLIF(SUM(IFF(LABEL = 'REJECT', 1, 0)), 0) AS RECALL_AT_50,
       CURRENT_TIMESTAMP() AS EVALUATED_AT
FROM scored;

-- Latest-day score per exporter (label unknown, so excluded from features).
CREATE TABLE ML.REJECT_RISK_SCORES AS
WITH latest AS (
  SELECT * FROM ML.REJECT_FEATURES
  QUALIFY ROW_NUMBER() OVER (PARTITION BY ENTITY_ID ORDER BY EVENT_DATE DESC) = 1
), scored AS (
  SELECT ENTITY_ID, EVENT_DATE,
         ML.REJECT_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'RISK_TIER', RISK_TIER, 'EXPORTER_AGE_YEARS', EXPORTER_AGE_YEARS,
           'DOC_DISCREPANCY_PCT', DOC_DISCREPANCY_PCT, 'AVG_CERT_TURNAROUND_HRS', AVG_CERT_TURNAROUND_HRS,
           'DOC_DISCREPANCY_7D', DOC_DISCREPANCY_7D, 'REJECTED_30D', REJECTED_30D)) AS P
  FROM latest
)
SELECT ENTITY_ID, EVENT_DATE AS SCORED_AS_OF,
       ROUND(P:probability:REJECT::FLOAT, 4) AS REJECT_PROB_7D,
       CASE WHEN P:probability:REJECT::FLOAT >= 0.5 THEN 'High'
            WHEN P:probability:REJECT::FLOAT >= 0.25 THEN 'Medium' ELSE 'Low' END AS RISK_BAND,
       CURRENT_TIMESTAMP() AS SCORED_AT
FROM scored;

-- All-exporter shipment-issue forecast (14 days) from the daily series, for export quality desk staffing.
CREATE VIEW ML.DAILY_ISSUES AS
SELECT EVENT_DATE::TIMESTAMP_NTZ AS TS, SUM(ISSUE_COUNT)::FLOAT AS ISSUE_COUNT
FROM RAW.EXPORTER_DAILY GROUP BY EVENT_DATE;

CREATE SNOWFLAKE.ML.FORECAST ML.ISSUE_FORECAST_MODEL(
  INPUT_DATA => TABLE(ML.DAILY_ISSUES),
  TIMESTAMP_COLNAME => 'TS',
  TARGET_COLNAME => 'ISSUE_COUNT'
);

CREATE TABLE ML.ISSUE_FORECAST AS
SELECT TS::DATE AS FORECAST_DATE, GREATEST(0, FORECAST) AS ISSUE_COUNT,
       GREATEST(0, LOWER_BOUND) AS LOWER_BOUND, UPPER_BOUND
FROM TABLE(ML.ISSUE_FORECAST_MODEL!FORECAST(FORECASTING_PERIODS => 14));
